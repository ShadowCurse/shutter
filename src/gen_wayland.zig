fn Array(comptime T: type, comptime capacity: u16) type {
  comptime assert(capacity < NONE);
  return struct {
    items: [capacity]T = undefined,
    count: u16 = 0,

    fn append(array: *@This(), item: T) !void {
      if (capacity <= array.count) return error.CapacityExceeded;
      array.items[array.count] = item;
      array.count += 1;
    }

    fn last(array: *@This()) !*T {
      if (array.count == 0) return error.InvalidXml;
      return &array.items[array.count - 1];
    }

    fn slice(array: anytype, range: Range) @TypeOf(array.items[0..array.count]) {
      assert(range.first <= array.count);
      assert(range.count <= array.count - range.first);
      return array.items[range.first..][0..range.count];
    }
  };
}

const Database = struct {
  protocols: Array(Protocol, 16) = .{},
  interfaces: Array(Interface, 128) = .{},
