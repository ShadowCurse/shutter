  try std.testing.expectEqual(3, db.messages.count);
  try std.testing.expectEqual(4, db.args.count);
  try std.testing.expectEqual(2, db.enums.count);
  try std.testing.expectEqual(6, db.entries.count);

  const display = &db.interfaces.items[0];
  try std.testing.expectEqualStrings("core\n      object", display.summary);
  try std.testing.expectEqualStrings("bind", db.messages.items[0].summary);
  try std.testing.expect(db.messages.items[2].destructor);

